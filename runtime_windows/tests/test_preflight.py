    def test_scope_and_production_entry_static_boundaries(self):
        tree = ast.parse((PRODUCT / 'runtime_windows/preflight.py').read_text(encoding='utf-8'))
        entry = next(node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == 'run_preflight')
        text = ast.get_source_segment((PRODUCT / 'runtime_windows/preflight.py').read_text(encoding='utf-8'), entry)
        self.assertLess(text.index('verify_preflight_binding'), text.index('_sequence('))
        self.assertIn('PinnedPreparationAuthority', text)
        self.assertNotIn('CandidateHost', text)
        self.assertNotIn('Popen', text)
        self.assertNotIn('INSTALL_ACCEPTED', text)



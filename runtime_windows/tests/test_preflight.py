        with mock.patch('runtime_windows.probe_backend.evaluate_parent_probe', return_value=expectation()):
            self.assertFalse(preflight.evaluate_probe_receipt(request, receipt)['runtime_authorized'])
        receipt['independent_readback']['size'] = True

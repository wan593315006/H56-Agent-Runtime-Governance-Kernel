class PreflightPureTests(unittest.TestCase):
    def setUp(self):
        self.guard = mock.patch.object(builtins, '__import__', side_effect=deny_effects)
        self.guard.start()

    def tearDown(self):
        self.guard.stop()

    def invalid(self, value):
        with self.assertRaises(PreparationError):
            preflight.validate_preflight_plan(value)

    def sequence(self, plan=None, receipt_change=None, probe_result=None, archive=None, clock=None):
        data = proposal() if plan is None else plan
        frozen = preflight.validate_preflight_plan(data)
        called = []
        def observe(request):
            called.append('observation')
            value = synthetic_observer_receipt(request)
            if receipt_change:
                receipt_change(value)
            return value
        def probe(request):
            called.append(request['check'])
            return {'SYNTHETIC_TEST_DOUBLE_ONLY': request['check']}
        def record(ordinal, value, room):
            raw = launch_contract.canonical(preflight.public_report(value))
            return dict(size=len(raw), sha256=hashlib.sha256(raw).hexdigest())
        with mock.patch.object(preflight, 'evaluate_probe_receipt',
                               side_effect=lambda request, raw: expectation(probe_result or 'RAW_EXPECTATION_MET_PENDING_ACCEPTANCE')):
            result = preflight._sequence(frozen, observe, probe, archive or record,
                clock or (lambda: 0.0), 'TEST_DOUBLE_ONLY')
        return result, called

    def test_plan_immutable_and_does_not_authorize(self):
        data = proposal()
        plan = preflight.validate_preflight_plan(data)
        before = plan.sha256
        data['session_id'] = 'changed'
        self.assertEqual(before, plan.sha256)
        self.assertNotIn('approved', plan.decoded())

    def test_extra_field_rejected(self):
        data = proposal(); data['approved'] = True
        self.invalid(data)

    def test_missing_probe_rejected(self):
        data = proposal(); del data['probe_requests']['read_only_source']
        self.invalid(data)

    def test_future_readback_hash_not_substitutable(self):
        data = proposal(); data['prelaunch_readback_sha256'] = '2' * 64
        self.invalid(data)

    def test_one_policy_for_all_children(self):
        data = proposal()
        data['probe_requests']['file_access_negative']['observation_policy']['cpu_rate_hundredths'] = 999
        self.invalid(data)

    def test_source_and_runtime_identities_must_match(self):
        for field, member in (('source_identity', 'product_manifest_sha256'), ('runtime', 'closure_sha256')):
            data = proposal()
            data['probe_requests']['file_access_negative'][field][member] = '2' * 64
            self.invalid(data)

    def test_unique_run_ids(self):
        data = proposal()
        item = data['probe_requests']['file_access_negative']
        item['run_id'] = data['observer_request']['run_id']
        item['environment']['H56_RUN_ID'] = item['run_id']
        self.invalid(data)

    def test_session_root_and_evidence_cannot_redirect(self):
        for field in ('product_root', 'evidence_root'):
            data = proposal(); data[field] = 'C:\\unapproved'
            self.invalid(data)
        data = proposal(); data['probe_requests']['file_access_negative']['session_id'] = 'other'
        self.invalid(data)

    def test_aggregate_time_and_disk_budgets(self):
        for limits in (dict(elapsed_ms=1000, archive_bytes=1024),
                       dict(elapsed_ms=True, archive_bytes=1024),
                       dict(elapsed_ms=90000, archive_bytes=preflight.MAX_ARCHIVE + 1)):
            data = proposal(); data['limits'] = limits
            self.invalid(data)

    def test_observer_revalidated_from_raw_not_status(self):
        request = observer_request()
        receipt = synthetic_observer_receipt(request)
        result = preflight.evaluate_observer_receipt(request, receipt)
        self.assertFalse(result['isolation_verified'])
        receipt['raw_stdout'] = b'FORGED_STATUS_IS_NOT_AN_OBSERVATION'
        receipt['observed_output_bytes']['stdout'] = len(receipt['raw_stdout'])
        with self.assertRaises(PreparationError):
            preflight.evaluate_observer_receipt(request, receipt)

    def test_fixed_sequence_complete_never_accepts_isolation(self):
        result, called = self.sequence()
        self.assertEqual(['observation'] + list(preflight.CHECKS), called)
        self.assertEqual('RAW_PREFLIGHT_COMPLETE_PENDING_HUMAN_ACCEPTANCE', result['status'])
        self.assertEqual('TEST_DOUBLE_ONLY', result['evidence_grade'])
        self.assertFalse(result['runtime_authorized'])
        self.assertFalse(result['isolation_accepted'])
        self.assertEqual('NOT_RUN', result['candidate_computation'])

    def test_nonzero_observer_stops_before_first_probe(self):
        result, called = self.sequence(receipt_change=lambda value: value.update(exit_code=5))
        self.assertEqual(['observation'], called)
        self.assertEqual('STOPPED', result['status'])
        self.assertEqual({'NOT_RUN'}, set(result['checks'].values()))

    def test_unknown_cleanup_cannot_continue(self):
        result, called = self.sequence(receipt_change=lambda value: value.update(cleanup=dict(status='UNKNOWN_LEAK_POSSIBLE')))
        self.assertEqual(['observation'], called)
        self.assertEqual('STOPPED', result['status'])

    def test_truncated_capture_cannot_continue(self):
        result, called = self.sequence(receipt_change=lambda value: value['capture_prefix_truncated'].update(stdout=True))
        self.assertEqual(['observation'], called)
        self.assertIn('CAPTURE_TRUNCATED', result['stop_reason'])

    def test_failed_or_unknown_probe_stops_batch(self):
        for status in ('FAIL', 'UNKNOWN'):
            result, called = self.sequence(probe_result=status)
            self.assertEqual(['observation', preflight.CHECKS[0]], called)
            self.assertEqual(status, result['checks'][preflight.CHECKS[0]])
            self.assertEqual('NOT_RUN', result['checks'][preflight.CHECKS[1]])

    def test_archive_failure_preserves_raw_and_stops(self):
        def bad_archive(ordinal, entry, room):
            raise OSError('SYNTHETIC_DISK_FULL')
        result, called = self.sequence(archive=bad_archive)
        self.assertEqual(['observation'], called)
        self.assertEqual('STOPPED_ARCHIVE_FAILED', result['status'])
        self.assertIsInstance(result['trace'][0]['receipt']['raw_stdout'], bytes)

    def test_invalid_archive_accounting_stops(self):
        result, called = self.sequence(archive=lambda *args: dict(size=0, sha256='1' * 64))
        self.assertEqual(['observation'], called)
        self.assertEqual('STOPPED_ARCHIVE_FAILED', result['status'])

    def test_deadline_stops_without_retry(self):
        values = iter((0.0, 100.0, 100.0))
        result, called = self.sequence(clock=lambda: next(values))
        self.assertEqual([], called)
        self.assertEqual('PREFLIGHT_ELAPSED_BUDGET', result['stop_reason'])

    def test_raw_json_representation_is_lossless(self):
        value = preflight.public_report(dict(raw=b'\x00\xfffixture\r\n'))['raw']
        self.assertEqual(b'\x00\xfffixture\r\n', base64.b64decode(value['value']))
        self.assertEqual(hashlib.sha256(b'\x00\xfffixture\r\n').hexdigest(), value['sha256'])
        with self.assertRaises(PreparationError):
            preflight.public_report(dict(raw=object()))

    def test_fixed_archive_filename_write_once(self):
        EVIDENCE.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix='pf_', dir=str(EVIDENCE)) as directory:
            root = Path(directory)
            result = preflight._new_archive(root, 0, dict(raw=b'fixture', member='../../ignored'), 1024)
            self.assertEqual('preflight_00.json', result['filename'])
            self.assertEqual({'preflight_00.json'}, {path.name for path in root.iterdir()})
            with self.assertRaises(FileExistsError):
                preflight._new_archive(root, 0, dict(raw=b'changed'), 1024)

    def test_duplicate_claim_refuses_before_any_producer(self):
        EVIDENCE.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix='claim_', dir=str(EVIDENCE)) as directory:
            root = Path(directory)
            plan = preflight.validate_preflight_plan(proposal())
            result = preflight._claim_run(root, plan)
            self.assertEqual('preflight_claim.json', result['filename'])
            with self.assertRaises(PreparationError) as failure:
                preflight._claim_run(root, plan)
            self.assertEqual('PREFLIGHT_DUPLICATE_RUN_CLAIM_REFUSED', failure.exception.code)

    def test_existing_receipt_slot_refuses_new_claim(self):
        EVIDENCE.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix='slot_', dir=str(EVIDENCE)) as directory:
            root = Path(directory)
            (root / 'preflight_03.json').write_bytes(b'SYNTHETIC_PRIOR_EVIDENCE')
            with self.assertRaises(PreparationError):
                preflight._claim_run(root, preflight.validate_preflight_plan(proposal()))
            self.assertFalse((root / 'preflight_claim.json').exists())

    def test_incomplete_parent_event_chain_stops(self):
        result, called = self.sequence(receipt_change=lambda value: value.update(events=['OWNED_CHILD_RESUMED']))
        self.assertEqual(['observation'], called)
        self.assertEqual('PREFLIGHT_PARENT_EVENT_CHAIN_INCOMPLETE', result['stop_reason'])

    def test_network_parent_positive_control_is_required(self):
        request = proposal()['probe_requests']['network_access_negative']

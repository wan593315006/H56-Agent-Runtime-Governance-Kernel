    def test_network_parent_transcript_bound_to_own_endpoint(self):
        request = proposal()['probe_requests']['network_access_negative']
        target = request['target']
        challenge = hashlib.sha256(('H56_LOOPBACK:' + target['sentinel_id']).encode()).digest()
        positive = dict(schema='h56.windows-loopback-positive.v1',
            status='HOST_ROUNDTRIP_OBSERVED', address=target['address'], port=target['port'],
            sentinel_id=target['sentinel_id'], challenge_sha256=hashlib.sha256(challenge).hexdigest())
        target['positive_receipt_sha256'] = hashlib.sha256(launch_contract.canonical(positive)).hexdigest()
        receipt = synthetic_probe_receipt(request); receipt['positive_control'] = positive
        with mock.patch('runtime_windows.probe_backend.evaluate_parent_probe', return_value=expectation()) as shared:
            result = preflight.evaluate_probe_receipt(request, receipt)
            self.assertFalse(result['isolation_accepted'])
            shared.assert_called_once()
        receipt['positive_control']['port'] += 1
        with self.assertRaises(PreparationError):
            preflight.evaluate_probe_receipt(request, receipt)

    def test_profile_requires_independent_parent_readback(self):
        request = proposal()['probe_requests']['profile_storage_scope']
        receipt = synthetic_probe_receipt(request)
        with mock.patch('runtime_windows.probe_backend.evaluate_parent_probe') as shared:
            with self.assertRaises(PreparationError):
                preflight.evaluate_probe_receipt(request, receipt)
            shared.assert_not_called()
        target = request['target']

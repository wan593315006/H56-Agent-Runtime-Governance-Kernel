def deny_effects(name, globals=None, locals=None, fromlist=(), level=0):
    full = importlib.util.resolve_name('.' * level + name, globals['__package__']) if level else name
    if any(full == prefix or full.startswith(prefix + '.') for prefix in FORBIDDEN):
        raise AssertionError('Pure preflight test forbidden import: ' + full)
    return ORIGINAL_IMPORT(name, globals, locals, fromlist, level)


